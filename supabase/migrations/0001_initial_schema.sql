BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Tables (4 clean-slate tables in public; plain TEXT XML; no public sharing)
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.mindmaps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  title VARCHAR(512) NOT NULL,
  description VARCHAR(512) DEFAULT '',
  xml TEXT NOT NULL,
  properties TEXT NOT NULL DEFAULT '{"zoom":0.8}',
  starred BOOLEAN NOT NULL DEFAULT FALSE,
  version INTEGER NOT NULL DEFAULT 1 CONSTRAINT mindmaps_version_positive CHECK (version >= 1),
  last_modification_by TEXT NOT NULL DEFAULT '',
  creation_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_modification_time TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.mindmap_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mindmap_id BIGINT NOT NULL REFERENCES public.mindmaps(id) ON DELETE CASCADE,
  owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  xml TEXT NOT NULL,
  editor_name TEXT NOT NULL DEFAULT '',
  creation_time TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.labels (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  title VARCHAR(30) NOT NULL,
  color VARCHAR(7) NOT NULL,
  parent_label_id BIGINT REFERENCES public.labels(id) ON DELETE CASCADE,
  creation_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT labels_owner_id_title_unique UNIQUE (owner_id, title),
  CONSTRAINT labels_no_self_parent CHECK (parent_label_id IS NULL OR parent_label_id <> id)
);

CREATE TABLE IF NOT EXISTS public.mindmap_labels (
  mindmap_id BIGINT NOT NULL REFERENCES public.mindmaps(id) ON DELETE CASCADE,
  label_id BIGINT NOT NULL REFERENCES public.labels(id) ON DELETE CASCADE,
  owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  PRIMARY KEY (mindmap_id, label_id)
);

-- -----------------------------------------------------------------------------
-- 2. Indexes (All FK columns + common query/sort paths)
-- -----------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS mindmaps_owner_id_last_mod_idx
  ON public.mindmaps (owner_id, last_modification_time DESC);

CREATE INDEX IF NOT EXISTS mindmap_history_mindmap_id_creation_idx
  ON public.mindmap_history (mindmap_id, creation_time DESC);

CREATE INDEX IF NOT EXISTS mindmap_history_owner_id_idx
  ON public.mindmap_history (owner_id);

CREATE INDEX IF NOT EXISTS labels_owner_id_idx
  ON public.labels (owner_id);

CREATE INDEX IF NOT EXISTS labels_parent_label_id_idx
  ON public.labels (parent_label_id);

CREATE INDEX IF NOT EXISTS mindmap_labels_label_id_idx
  ON public.mindmap_labels (label_id);

CREATE INDEX IF NOT EXISTS mindmap_labels_owner_id_idx
  ON public.mindmap_labels (owner_id);

-- -----------------------------------------------------------------------------
-- 3. Row-Level Security (Enable & Force on all 4 tables)
-- -----------------------------------------------------------------------------

ALTER TABLE public.mindmaps ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mindmaps FORCE ROW LEVEL SECURITY;

ALTER TABLE public.mindmap_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mindmap_history FORCE ROW LEVEL SECURITY;

ALTER TABLE public.labels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.labels FORCE ROW LEVEL SECURITY;

ALTER TABLE public.mindmap_labels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mindmap_labels FORCE ROW LEVEL SECURITY;

-- -----------------------------------------------------------------------------
-- 4. Least-Privilege Grants (Revoke anon/public; grant DML to authenticated)
-- -----------------------------------------------------------------------------

GRANT USAGE ON SCHEMA public TO authenticated, service_role;

REVOKE ALL ON TABLE public.mindmaps FROM anon, PUBLIC;
REVOKE ALL ON TABLE public.mindmap_history FROM anon, PUBLIC;
REVOKE ALL ON TABLE public.labels FROM anon, PUBLIC;
REVOKE ALL ON TABLE public.mindmap_labels FROM anon, PUBLIC;

REVOKE ALL ON SEQUENCE public.mindmaps_id_seq FROM anon, PUBLIC;
REVOKE ALL ON SEQUENCE public.mindmap_history_id_seq FROM anon, PUBLIC;
REVOKE ALL ON SEQUENCE public.labels_id_seq FROM anon, PUBLIC;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.mindmaps TO authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.mindmap_history TO authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.labels TO authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.mindmap_labels TO authenticated, service_role;

GRANT USAGE, SELECT ON SEQUENCE public.mindmaps_id_seq TO authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.mindmap_history_id_seq TO authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.labels_id_seq TO authenticated, service_role;

-- -----------------------------------------------------------------------------
-- 5. RLS Policies (TO authenticated only; initPlan (SELECT auth.uid()) pattern)
-- -----------------------------------------------------------------------------

-- 5.1 public.mindmaps
DROP POLICY IF EXISTS mindmaps_select_own ON public.mindmaps;
CREATE POLICY mindmaps_select_own
  ON public.mindmaps
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id);

DROP POLICY IF EXISTS mindmaps_insert_own ON public.mindmaps;
CREATE POLICY mindmaps_insert_own
  ON public.mindmaps
  FOR INSERT
  TO authenticated
  WITH CHECK ((SELECT auth.uid()) = owner_id);

DROP POLICY IF EXISTS mindmaps_update_own ON public.mindmaps;
CREATE POLICY mindmaps_update_own
  ON public.mindmaps
  FOR UPDATE
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id)
  WITH CHECK ((SELECT auth.uid()) = owner_id);

DROP POLICY IF EXISTS mindmaps_delete_own ON public.mindmaps;
CREATE POLICY mindmaps_delete_own
  ON public.mindmaps
  FOR DELETE
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id);

-- 5.2 public.mindmap_history (plus cross-table owner check on mindmaps)
DROP POLICY IF EXISTS mindmap_history_select_own ON public.mindmap_history;
CREATE POLICY mindmap_history_select_own
  ON public.mindmap_history
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id);

DROP POLICY IF EXISTS mindmap_history_insert_own ON public.mindmap_history;
CREATE POLICY mindmap_history_insert_own
  ON public.mindmap_history
  FOR INSERT
  TO authenticated
  WITH CHECK (
    (SELECT auth.uid()) = owner_id
    AND EXISTS (
      SELECT 1
      FROM public.mindmaps m
      WHERE m.id = mindmap_id
        AND m.owner_id = (SELECT auth.uid())
    )
  );

DROP POLICY IF EXISTS mindmap_history_update_own ON public.mindmap_history;
CREATE POLICY mindmap_history_update_own
  ON public.mindmap_history
  FOR UPDATE
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id)
  WITH CHECK (
    (SELECT auth.uid()) = owner_id
    AND EXISTS (
      SELECT 1
      FROM public.mindmaps m
      WHERE m.id = mindmap_id
        AND m.owner_id = (SELECT auth.uid())
    )
  );

DROP POLICY IF EXISTS mindmap_history_delete_own ON public.mindmap_history;
CREATE POLICY mindmap_history_delete_own
  ON public.mindmap_history
  FOR DELETE
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id);

-- 5.3 public.labels (split per command to avoid 42P17 self-recursion on parent_label_id)
DROP POLICY IF EXISTS labels_select_own ON public.labels;
CREATE POLICY labels_select_own
  ON public.labels
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id);

DROP POLICY IF EXISTS labels_insert_own ON public.labels;
CREATE POLICY labels_insert_own
  ON public.labels
  FOR INSERT
  TO authenticated
  WITH CHECK (
    (SELECT auth.uid()) = owner_id
    AND (
      parent_label_id IS NULL
      OR EXISTS (
        SELECT 1
        FROM public.labels p
        WHERE p.id = parent_label_id
          AND p.owner_id = (SELECT auth.uid())
      )
    )
  );

DROP POLICY IF EXISTS labels_update_own ON public.labels;
CREATE POLICY labels_update_own
  ON public.labels
  FOR UPDATE
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id)
  WITH CHECK (
    (SELECT auth.uid()) = owner_id
    AND (
      parent_label_id IS NULL
      OR EXISTS (
        SELECT 1
        FROM public.labels p
        WHERE p.id = parent_label_id
          AND p.owner_id = (SELECT auth.uid())
      )
    )
  );

DROP POLICY IF EXISTS labels_delete_own ON public.labels;
CREATE POLICY labels_delete_own
  ON public.labels
  FOR DELETE
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id);

-- 5.4 public.mindmap_labels (plus cross-table owner check on both mindmaps & labels)
DROP POLICY IF EXISTS mindmap_labels_select_own ON public.mindmap_labels;
CREATE POLICY mindmap_labels_select_own
  ON public.mindmap_labels
  FOR SELECT
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id);

DROP POLICY IF EXISTS mindmap_labels_insert_own ON public.mindmap_labels;
CREATE POLICY mindmap_labels_insert_own
  ON public.mindmap_labels
  FOR INSERT
  TO authenticated
  WITH CHECK (
    (SELECT auth.uid()) = owner_id
    AND EXISTS (
      SELECT 1
      FROM public.mindmaps m
      WHERE m.id = mindmap_id
        AND m.owner_id = (SELECT auth.uid())
    )
    AND EXISTS (
      SELECT 1
      FROM public.labels l
      WHERE l.id = label_id
        AND l.owner_id = (SELECT auth.uid())
    )
  );

DROP POLICY IF EXISTS mindmap_labels_update_own ON public.mindmap_labels;
CREATE POLICY mindmap_labels_update_own
  ON public.mindmap_labels
  FOR UPDATE
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id)
  WITH CHECK (
    (SELECT auth.uid()) = owner_id
    AND EXISTS (
      SELECT 1
      FROM public.mindmaps m
      WHERE m.id = mindmap_id
        AND m.owner_id = (SELECT auth.uid())
    )
    AND EXISTS (
      SELECT 1
      FROM public.labels l
      WHERE l.id = label_id
        AND l.owner_id = (SELECT auth.uid())
    )
  );

DROP POLICY IF EXISTS mindmap_labels_delete_own ON public.mindmap_labels;
CREATE POLICY mindmap_labels_delete_own
  ON public.mindmap_labels
  FOR DELETE
  TO authenticated
  USING ((SELECT auth.uid()) = owner_id);

COMMIT;
