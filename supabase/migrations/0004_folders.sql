BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Create public.folders table (hierarchical, single-owner)
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.folders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL,
  parent_id BIGINT REFERENCES public.folders(id) ON DELETE SET NULL,
  creation_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_time TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'folders_name_not_blank'
      AND conrelid = 'public.folders'::regclass
  ) THEN
    ALTER TABLE public.folders
      ADD CONSTRAINT folders_name_not_blank CHECK (char_length(btrim(name)) > 0);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'folders_no_self_parent'
      AND conrelid = 'public.folders'::regclass
  ) THEN
    ALTER TABLE public.folders
      ADD CONSTRAINT folders_no_self_parent CHECK (parent_id IS NULL OR parent_id <> id);
  END IF;
END $$;

-- Sibling uniqueness for both root folders (parent_id IS NULL) and nested folders
CREATE UNIQUE INDEX IF NOT EXISTS folders_owner_root_name_unique
  ON public.folders (owner_id, name)
  WHERE parent_id IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS folders_owner_parent_name_unique
  ON public.folders (owner_id, parent_id, name)
  WHERE parent_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS folders_owner_id_idx
  ON public.folders (owner_id);

CREATE INDEX IF NOT EXISTS folders_parent_id_idx
  ON public.folders (parent_id);

-- -----------------------------------------------------------------------------
-- 2. Add folder_id column & FK index on public.mindmaps
-- -----------------------------------------------------------------------------

ALTER TABLE public.mindmaps
  ADD COLUMN IF NOT EXISTS folder_id BIGINT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'mindmaps_folder_id_fkey'
      AND conrelid = 'public.mindmaps'::regclass
  ) THEN
    ALTER TABLE public.mindmaps
      ADD CONSTRAINT mindmaps_folder_id_fkey
      FOREIGN KEY (folder_id) REFERENCES public.folders(id) ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS mindmaps_folder_id_idx
  ON public.mindmaps (folder_id);

CREATE INDEX IF NOT EXISTS mindmaps_owner_id_folder_id_idx
  ON public.mindmaps (owner_id, folder_id);

-- -----------------------------------------------------------------------------
-- 3. Row-Level Security & Least-Privilege Grants for public.folders
-- -----------------------------------------------------------------------------

ALTER TABLE public.folders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.folders FORCE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.folders FROM anon, PUBLIC;
REVOKE ALL ON SEQUENCE public.folders_id_seq FROM anon, PUBLIC;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.folders TO authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.folders_id_seq TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.is_valid_parent_folder(p_parent_id BIGINT, p_owner_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT p_parent_id IS NULL OR (
    p_owner_id = (SELECT auth.uid())
    AND EXISTS (
      SELECT 1 FROM public.folders WHERE id = p_parent_id AND owner_id = p_owner_id
    )
  );
$$;

REVOKE ALL ON FUNCTION public.is_valid_parent_folder(BIGINT, UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_valid_parent_folder(BIGINT, UUID) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.is_valid_mindmap_folder(p_folder_id BIGINT, p_owner_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT p_folder_id IS NULL OR (
    p_owner_id = (SELECT auth.uid())
    AND EXISTS (
      SELECT 1 FROM public.folders WHERE id = p_folder_id AND owner_id = p_owner_id
    )
  );
$$;

REVOKE ALL ON FUNCTION public.is_valid_mindmap_folder(BIGINT, UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_valid_mindmap_folder(BIGINT, UUID) TO authenticated, service_role;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'folders' AND policyname = 'folders_select_own'
  ) THEN
    CREATE POLICY folders_select_own
      ON public.folders
      FOR SELECT
      TO authenticated
      USING ((SELECT auth.uid()) = owner_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'folders' AND policyname = 'folders_insert_own'
  ) THEN
    CREATE POLICY folders_insert_own
      ON public.folders
      FOR INSERT
      TO authenticated
      WITH CHECK (
        (SELECT auth.uid()) = owner_id
        AND public.is_valid_parent_folder(parent_id, (SELECT auth.uid()))
      );
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'folders' AND policyname = 'folders_update_own'
  ) THEN
    CREATE POLICY folders_update_own
      ON public.folders
      FOR UPDATE
      TO authenticated
      USING ((SELECT auth.uid()) = owner_id)
      WITH CHECK (
        (SELECT auth.uid()) = owner_id
        AND public.is_valid_parent_folder(parent_id, (SELECT auth.uid()))
      );
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'folders' AND policyname = 'folders_delete_own'
  ) THEN
    CREATE POLICY folders_delete_own
      ON public.folders
      FOR DELETE
      TO authenticated
      USING ((SELECT auth.uid()) = owner_id);
  END IF;
END $$;

-- Enforce folder ownership on mindmaps INSERT/UPDATE without dropping existing policies
ALTER POLICY mindmaps_insert_own ON public.mindmaps
  WITH CHECK (
    (SELECT auth.uid()) = owner_id
    AND public.is_valid_mindmap_folder(folder_id, (SELECT auth.uid()))
  );

ALTER POLICY mindmaps_update_own ON public.mindmaps
  USING ((SELECT auth.uid()) = owner_id)
  WITH CHECK (
    (SELECT auth.uid()) = owner_id
    AND public.is_valid_mindmap_folder(folder_id, (SELECT auth.uid()))
  );

-- -----------------------------------------------------------------------------
-- 4. Backfill existing mindmaps.folder_path strings into public.folders
-- -----------------------------------------------------------------------------

DO $$
DECLARE
  rec RECORD;
  seg TEXT;
  segments TEXT[];
  cur_parent_id BIGINT;
  found_id BIGINT;
  normalized_path TEXT;
BEGIN
  FOR rec IN
    SELECT id, owner_id, folder_path
    FROM public.mindmaps
    WHERE folder_id IS NULL
      AND btrim(folder_path) <> ''
  LOOP
    segments := string_to_array(btrim(rec.folder_path, '/ '), '/');
    cur_parent_id := NULL;
    normalized_path := '';

    FOREACH seg IN ARRAY segments LOOP
      seg := btrim(seg);
      IF seg = '' THEN
        CONTINUE;
      END IF;
      seg := left(seg, 100);
      normalized_path := normalized_path || seg || '/';

      IF cur_parent_id IS NULL THEN
        SELECT id INTO found_id
        FROM public.folders
        WHERE owner_id = rec.owner_id AND parent_id IS NULL AND name = seg
        LIMIT 1;
      ELSE
        SELECT id INTO found_id
        FROM public.folders
        WHERE owner_id = rec.owner_id AND parent_id = cur_parent_id AND name = seg
        LIMIT 1;
      END IF;

      IF found_id IS NULL THEN
        INSERT INTO public.folders (owner_id, name, parent_id)
        VALUES (rec.owner_id, seg, cur_parent_id)
        RETURNING id INTO found_id;
      END IF;

      cur_parent_id := found_id;
    END LOOP;

    IF cur_parent_id IS NOT NULL THEN
      UPDATE public.mindmaps
      SET folder_id = cur_parent_id,
          folder_path = normalized_path
      WHERE id = rec.id;
    END IF;
  END LOOP;
END $$;

COMMIT;
